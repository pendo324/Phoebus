import Foundation

/// Apollo's named accent-colour themes (18, each with an independent
/// light/dark toggle) and named comment-depth palettes (Blep, Combustion,
/// Forest, Nuit, Ocean, Rainbow, each with Light/Dark 7-colour hex arrays).
/// A `Theme` pairs one accent theme with one palette; Apollo lets the two
/// vary independently.
public struct Theme: Codable, Sendable, Equatable, Identifiable {
    public var id: String
    public var name: String
    /// Hex string like "FF6B35", applied via `.tint()` across the app.
    public var accentColorHex: String
    /// Colors cycled through by comment depth (root, then each reply
    /// level) for the left-edge depth indicator.
    public var commentDepthColorHexes: [String]
    /// Which named `CommentColorPalette` this theme pairs with. Stored
    /// so the real "Comments Theme" row can show the theme's own
    /// palette name when no override is set, and so an override can be
    /// expressed as a palette NAME rather than a copy of its hexes
    /// (which would silently go stale against the palette data).
    /// Optional: themes generated by AI or imported via QR carry custom
    /// hexes with no named palette.
    public var commentPaletteName: String?
    /// Whether this variant targets dark appearance. Two themes with
    /// the same `name` but different `isDark` form a real light/dark
    /// pair, matching Apollo's actual theme structure.
    public var isDark: Bool
    /// `true` for a theme generated via `ThemeGenerationClient` (AI)
    /// or imported via QR code, rather than one of the bundled
    /// built-ins — used by the UI to group/label them separately.
    public var isGenerated: Bool
    /// "Colourize Vote Arrows": idle arrows use the accent colour, but
    /// a cast vote still shows Apollo's green/blue, since that pairing
    /// is the "you voted this way" signal and forcing both to the same
    /// accent would erase it.
    public var voteArrowsAccent: Bool

    public init(id: String, name: String, accentColorHex: String, commentDepthColorHexes: [String], isDark: Bool = false, isGenerated: Bool = false, commentPaletteName: String? = nil, voteArrowsAccent: Bool = false) {
        self.id = id
        self.name = name
        self.accentColorHex = accentColorHex
        self.commentDepthColorHexes = commentDepthColorHexes
        self.isDark = isDark
        self.isGenerated = isGenerated
        self.commentPaletteName = commentPaletteName
        self.voteArrowsAccent = voteArrowsAccent
    }

    /// Custom decode so themes persisted before `isDark`/`isGenerated`
    /// existed still decode successfully.
    public init(from decoder: Decoder) throws {
        let container = try decoder.container(keyedBy: CodingKeys.self)
        id = try container.decode(String.self, forKey: .id)
        name = try container.decode(String.self, forKey: .name)
        accentColorHex = try container.decode(String.self, forKey: .accentColorHex)
        commentDepthColorHexes = try container.decode([String].self, forKey: .commentDepthColorHexes)
        isDark = try container.decodeIfPresent(Bool.self, forKey: .isDark) ?? false
        isGenerated = try container.decodeIfPresent(Bool.self, forKey: .isGenerated) ?? false
        // Absent-tolerant: older persisted themes carry no palette name. `nil`
        // means "this theme's own custom hexes", which `CommentsThemeStore`
        // handles rather than falling back to Rainbow.
        commentPaletteName = try container.decodeIfPresent(String.self, forKey: .commentPaletteName)
        // Absent-tolerant like the fields above: defaults to off.
        voteArrowsAccent = try container.decodeIfPresent(Bool.self, forKey: .voteArrowsAccent) ?? false
    }

    private init(realName: String, accentColorHex: String, palette: String, isDark: Bool) {
        let variant = isDark ? "Dark" : "Light"
        self.id = "\(realName.lowercased().replacingOccurrences(of: " ", with: "_"))_\(variant.lowercased())"
        self.name = realName
        self.accentColorHex = accentColorHex
        self.commentDepthColorHexes = CommentColorPalette.hexes(named: palette, isDark: isDark)
        self.commentPaletteName = palette
        self.isDark = isDark
        self.isGenerated = false
        self.voteArrowsAccent = false
    }

