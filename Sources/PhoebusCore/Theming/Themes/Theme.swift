/// The "Comments Theme" row (Settings > Appearance > Theme Manager >
/// Options). Apollo keeps the comments palette separate from the accent
/// theme, so any pairing is possible. `nil` follows the selected theme's
/// own palette.
public enum CommentsThemeStore {
    private static let key = "com.pendo324.Phoebus.commentsThemePalette"

    /// The user's explicit palette override, or `nil` to follow the theme.
    public static var overridePaletteName: String? {
        get {
            guard let name = UserDefaults.standard.string(forKey: key),
                  CommentColorPalette.all[name] != nil else { return nil }
            return name
        }
        set {
            if let newValue, CommentColorPalette.all[newValue] != nil {
                UserDefaults.standard.set(newValue, forKey: key)
            } else {
                UserDefaults.standard.removeObject(forKey: key)
            }
        }
    }

    /// The palette name actually in effect: the override when set,
    /// otherwise the active theme's own palette.
    public static func effectivePaletteName(theme: Theme) -> String {
        overridePaletteName ?? theme.commentPaletteName ?? "Rainbow"
    }

    /// The depth colours to render comment indent bars with, honouring
    /// both the override and the theme's light/dark variant.
    public static func effectiveHexes(theme: Theme) -> [String] {
        // With no override, a generated/imported theme keeps its OWN
        // custom hexes - it has no named palette to look up, and
        // falling back to Rainbow would silently discard the colours
        // the user generated or imported.
        if let override = overridePaletteName {
            return CommentColorPalette.hexes(named: override, isDark: theme.isDark)
        }
        if theme.commentPaletteName == nil, !theme.commentDepthColorHexes.isEmpty {
            return theme.commentDepthColorHexes
        }
        return CommentColorPalette.hexes(named: effectivePaletteName(theme: theme), isDark: theme.isDark)
    }
}

public enum ThemeStore {
    private static let key = "com.pendo324.Phoebus.selectedThemeID"
    private static let generatedKey = "com.pendo324.Phoebus.generatedThemes"

    /// Per-theme "Colourize Vote Arrows", stored by theme ID rather than
    /// on the theme itself: `save` only persists the selected theme's
    /// ID and rebuilds the rest from the fixed catalog, so a flag on a
    /// built-in theme would otherwise be discarded on the next `load`.
    private static let voteArrowsAccentKey =
        "com.pendo324.Phoebus.themeVoteArrowsAccent"

    private static func voteArrowsAccentMap() -> [String: Bool] {
        UserDefaults.standard.dictionary(forKey: voteArrowsAccentKey) as? [String: Bool] ?? [:]
    }

    public static func load() -> Theme {
        guard let id = UserDefaults.standard.string(forKey: key),
              var theme = allAvailableThemes().first(where: { $0.id == id }) else {
            return .defaultLight
        }
        // A custom theme carries its own vote-arrow choice.
        if CustomTheme.parse(themeID: id) == nil {
            theme.voteArrowsAccent = voteArrowsAccentMap()[id] ?? false
        }
        return theme
    }

    /// Posted whenever the selected theme changes so live views re-render; a
    /// plain `UserDefaults` write is invisible to SwiftUI.
    public static let didChangeNotification = Notification.Name("com.pendo324.Phoebus.themeDidChange")

    public static func save(_ theme: Theme) {
        UserDefaults.standard.set(theme.id, forKey: key)
        var accents = voteArrowsAccentMap()
        accents[theme.id] = theme.voteArrowsAccent
        UserDefaults.standard.set(accents, forKey: voteArrowsAccentKey)
        defer { NotificationCenter.default.post(name: didChangeNotification, object: nil) }
        // Persist generated (AI/imported) themes so they survive
        // relaunch and reappear in the picker, unlike the fixed
        // built-in catalog.
        // Custom themes live in `CustomThemeStore`, not this list.
        if theme.isGenerated, CustomTheme.parse(themeID: theme.id) == nil {
            addGeneratedTheme(theme)
        }
    }

    /// All themes selectable in the UI: the fixed built-in gallery
    /// plus any AI-generated or QR-imported themes the user has kept.
    public static func allAvailableThemes() -> [Theme] {
        Theme.allThemes + loadGeneratedThemes() + CustomThemeStore.bridgedThemes()
    }

    public static func loadGeneratedThemes() -> [Theme] {
        // Decoded per theme so one unreadable entry doesn't lose the rest.
        guard let data = UserDefaults.standard.data(forKey: generatedKey),
              let themes = try? JSONDecoder().decode(LossyArray<Theme>.self, from: data) else {
            return []
        }
        return themes.elements
    }

    public static func addGeneratedTheme(_ theme: Theme) {
        var themes = loadGeneratedThemes().filter { $0.id != theme.id }
        themes.append(theme)
        saveGeneratedThemes(themes)
    }

    public static func removeGeneratedTheme(id: String) {
        let themes = loadGeneratedThemes().filter { $0.id != id }
        saveGeneratedThemes(themes)
    }

    private static func saveGeneratedThemes(_ themes: [Theme]) {
        guard let data = try? JSONEncoder().encode(themes) else { return }
        UserDefaults.standard.set(data, forKey: generatedKey)
    }
}
