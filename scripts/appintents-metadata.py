#!/usr/bin/env python3
"""Writes a target's Metadata.appintents on Linux, in place of Apple's
appintentsmetadataprocessor (macOS only).

Usage:
  scripts/appintents-metadata.py <out/Metadata.appintents> <file.swiftconstvalues>...
  scripts/appintents-metadata.py --self-test
  scripts/appintents-metadata.py --compare <fixtures dir>

iOS reads this metadata to find a bundle's App Intents: without it the
widget's configurable widgets get no settings (CHSErrorDomain 1103), and
the app's intents and App Shortcuts don't appear in Shortcuts, Siri or
Spotlight. The input is the compiler's const values for the target
(-emit-const-values, see Package.swift), which already hold what the
metadata needs: each type's mangled name, its conformances, availability,
and the literal titles, defaults, cases and phrases.

Only what Phoebus uses is supported:
- WidgetConfigurationIntents, and AppIntents whose perform() returns a
  result (plain, or with a dialog, a snippet, a snippet intent, or a
  String / [entity] value), with literal titles and descriptions
  (search keywords included), `supportedModes` and `isDiscoverable`, and
  the system intents OpenIntent, ShowInAppSearchResultsIntent (the
  `.general` scope) and SnippetIntent, declared as the assistant schemas
  `system.open` and `system.searchInApp` (`__appSchemaIntent`, what
  @AppIntent(schema:) expands to; the macro plugin only ships with Xcode,
  so the sources write the expansion out) or not;
- parameters that are String, [String], Bool, a String-backed AppEnum,
  an AppEntity of the target or a StringSearchCriteria (which may have no
  title), with literal defaults, and a Summary("...") showing every
  parameter;
- AppEntity and IndexedEntity types with literal display representations
  (a name, or name, numeric format and synonyms), @Property values of
  String, Int, Bool, Date and URL (with an indexing key), @DeferredProperty
  arrays of those or of the target's entities, and a Transferable URL /
  plain-text export, each with an EntityStringQuery (IndexedEntityQuery
  included);
- one AppShortcutsProvider with AppShortcut(intent:phrases:shortTitle:
  systemImageName:) entries whose phrases interpolate only the app name.
Anything else is an error rather than a guess, since iOS ignores or
rejects metadata it cannot match to the binary.

--self-test runs the generator on each Tests/Fixtures/AppIntents/<target>/
input.swiftconstvalues and compares the result with the output of Apple's
processor for the same input (Metadata.appintents next to it), then checks
that changes to the const values it cannot match to Apple's output are
refused. --compare does the comparison for any directory laid out like
that; the App Intents reference workflow runs it on fresh output from
Xcode 27. When a target's intents change, its fixture is regenerated by
that workflow (see docs/building-on-linux.md, "AppIntents metadata"); until
then the generator has not been verified for the new input.
Tests/Fixtures/AppIntents/Probe is Apple's output for the assistant schema
macros and deferred properties, from Tests/AppIntentsMacroProbe.
"""
