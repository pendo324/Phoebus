# The value-type identifiers of a primitive, by Swift type.
PRIMITIVES = {"Swift.String": 0, "Swift.Bool": 1, "Swift.Int": 2, "Foundation.Date": 8, "Foundation.URL": 11}
STRING, BOOL = PRIMITIVES["Swift.String"], PRIMITIVES["Swift.Bool"]
# Content types of what a Transferable entity exports, by what it is exported as.
EXPORTED_URL = "public.url"
EXPORTED_PLAIN_TEXT = {"plainText": "public.plain-text"}
# The assistant schemas an intent may declare with `__appSchemaIntent` (what
